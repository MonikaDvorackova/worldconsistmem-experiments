    w("- **D (conservative):** every response to a non-unique question counts as a failure.")
    w("- **E (bounds):** lower = D; mid = benchmark convention; upper = any single documented candidate event is "
      "credited. Listing several events (6 F0 CEO answers) and one F1 answer mixing two events stay uncredited.")
    w("")
    w("### 6.4 Where the arms actually differ")
    w("")
    w("| Subtype / structure | n | exact v2 (F0/F1/F2/F3) | semantic question-aligned | single documented event |")
