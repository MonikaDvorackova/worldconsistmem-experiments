"""Markdown rendering for scripts/round2_analysis.py (numbers come from the results dict only)."""

from __future__ import annotations

from typing import Any

ARMS = ("F0", "F1", "F2", "F3")


def _arm_row(s: dict[str, Any]) -> str:
    return " | ".join(f"{s['arms'][a]['k']}/{s['arms'][a]['n']}" for a in ARMS)


def _pair(s: dict[str, Any], c: str) -> str:
    p = s["paired"][c]
    if p["n_discordant"] == 0:
        return "0.0 (no discordant items)"
    return (f"{100 * p['delta']:+.1f} [{100 * p['ci95_lo']:+.1f}, {100 * p['ci95_hi']:+.1f}]; "
            f"{p['y_only']} vs {p['x_only']}; p={p['p_two_sided']:.2g}")


def _conf_table(m: dict[str, dict[str, int]], row_name: str, col_name: str) -> list[str]:
    labels = ("correct", "incorrect", "ambiguous")
    out = [f"| {row_name} \\ {col_name} | " + " | ".join(labels) + " | total |", "|---|---:|---:|---:|---:|"]
    for r in labels:
        out.append(f"| {r} | " + " | ".join(str(m[r][c]) for c in labels) + f" | {sum(m[r].values())} |")
    out.append("| total | " + " | ".join(str(sum(m[r][c] for r in labels)) for c in labels)
               + f" | {sum(sum(v.values()) for v in m.values())} |")
    return out


def render(res: dict[str, Any], audit: list[dict[str, Any]], adj: list[dict[str, Any]]) -> str:
    v, a2, a1 = res["validation"], res["agreement"]["round2"], res["agreement"]["round1"]
