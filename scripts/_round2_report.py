    for key, cell in st["cells"].items():
        n = cell["F0"]["n"]
        f = lambda m: " / ".join(str(cell[a].get(m, 0)) for a in ARMS)  # noqa: E731
        w(f"| {key.replace('|', ' / ')} | {n} | {f('exact_v2')} | {f('semantic_qa')} | {f('single_documented_event')} |")
    w("")
    w("For non-unique rows 'semantic question-aligned' means 'selected the latest event'. For document rows it is "
      "not a correctness measure at all.")
